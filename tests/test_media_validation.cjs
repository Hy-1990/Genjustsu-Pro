const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync('static/media-validation.js','utf8') + '\nthis.rules = MediaValidation;',context);
const rules = context.rules;
assert.equal(rules.fileError({name:'source.MP4',size:500_000_000},'source'),null);
assert.equal(rules.fileError({name:'source.mp4',size:500_000_001},'source'),'size_source');
assert.equal(rules.fileError({name:'source.png',size:10},'source'),'format_source');
assert.equal(rules.fileError({name:'identity.mov',size:100_000_001},'reference'),'size_reference');
assert.equal(rules.fileError({name:'identity.mp4',size:10},'second'),'format_second');
assert.equal(rules.fileError({name:'source.mp4',size:0},'source'),'empty_file');
assert.equal(rules.durationError(3.99,'source'),'duration_source');
assert.equal(rules.durationError(4,'source'),null);
assert.equal(rules.durationError(30,'source'),null);
assert.equal(rules.durationError(30.01,'source'),'duration_source');
assert.equal(rules.durationError(1.99,'reference'),'duration_reference');
assert.equal(rules.durationError(2,'reference',28),null);
assert.equal(rules.durationError(2,'reference',28.01),'reference_duration');
assert.equal(rules.durationError(Infinity,'source'),'invalid_video');
console.log('14 upload boundary assertions passed');
